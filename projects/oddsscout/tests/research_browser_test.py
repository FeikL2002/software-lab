"""Exercises the self-contained demo in a real Chromium browser. All sports data is fictional; storage and download clicks are simulated."""
from pathlib import Path
import json,os,re,shutil
from playwright.sync_api import sync_playwright,expect
ROOT=Path(__file__).resolve().parents[1]
OUT=Path(os.environ.get('RESEARCH_TEST_OUTPUT',str(ROOT/'test-output/research')));OUT.mkdir(parents=True,exist_ok=True)
FILE=Path(os.environ.get('RESEARCH_PREVIEW',str(ROOT/'OddsScout-My-Bets-Live-Interactive.html')))
HTML=FILE.read_text()
SCRIPTS='\n'.join(re.findall(r'<script\b[^>]*>(.*?)</script>',HTML,flags=re.S))
HTML=re.sub(r'<script\b[^>]*>.*?</script>','',HTML,flags=re.S)
PRE=r"""
const storage={getItem:k=>window.__store[k]??null,setItem:(k,v)=>window.__store[k]=String(v),removeItem:k=>delete window.__store[k]};
Object.defineProperty(window,'localStorage',{value:storage,configurable:true});
Object.defineProperty(window,'sessionStorage',{value:storage,configurable:true});
const create=URL.createObjectURL;URL.createObjectURL=(blob)=>{window.__export=blob;return create.call(URL,blob);};
const click=HTMLAnchorElement.prototype.click;HTMLAnchorElement.prototype.click=function(){if(this.download)return;return click.call(this);};
"""
results=[];errors=[]
def boot(page,store=None):
 page.set_content(HTML)
 page.evaluate('(s)=>window.__store=s',store or {})
 page.add_script_tag(content='(()=>{'+PRE+'})();')
 page.add_script_tag(content=SCRIPTS)

def check(name,value):
 if not value:raise AssertionError(name)
 results.append(name);print('PASS',name)
with sync_playwright() as pw:
 browser=pw.chromium.launch(executable_path=os.environ.get('CHROMIUM_PATH') or shutil.which('chromium'),headless=True,args=['--no-sandbox'])
 context=browser.new_context(viewport={'width':1440,'height':1080},accept_downloads=True)
 page=context.new_page();page.on('pageerror',lambda e:errors.append(str(e)))
 boot(page);page.locator('#confirm-age').click();expect(page.locator('.game-card')).to_have_count(27)
 check('Explicit age entry loads labeled fictional board','Fictional demo' in page.locator('#feed-pill').inner_text())
 check('Upcoming moneylines have actionable ticket buttons',page.locator('[data-add-leg]').count()>15)
 page.locator('.research-banner [data-open="research"]').click()
 check('Research opens as an interactive modal',page.locator('#research-dialog').evaluate('(d)=>d.open'))
 check('Demo research is labeled rules-based and fictional','Fictional demo' in page.locator('#research-mode').inner_text())
 check('No suggestions fabricated before history load',page.locator('.research-option').count()==0)
 page.locator('#research-analyze').click();expect(page.locator('.research-option')).to_have_count(3)
 check('History analysis produces three bounded research options',page.locator('.research-option').count()==3)
 check('Two-leg options are default',page.locator('.research-option').first.locator('.research-leg').count()==2)
 check('Candidate scan coverage is visible','8 selected' in page.locator('#research-status').inner_text())
 check('Recommendations do not claim a win percentage','win chance' not in page.locator('.research-option').first.inner_text().lower())
 page.locator('[data-use-plan="0"]').click()
 check('Review loads both legs into ticket',page.locator('.ticket-leg').count()==2)
 check('Each common sportsbook has a whole-ticket estimate',page.locator('.parlay-book').count()==4)
 check('Payout is explicitly not a book-confirmed parlay','NOT A BOOK-CONFIRMED PARLAY' in page.locator('#parlay-compare').inner_text())
 check('Copy and save become enabled',page.locator('#parlay-save').is_enabled() and page.locator('#parlay-copy').is_enabled())
 old=page.locator('.parlay-book').first.inner_text();page.locator('#parlay-stake').fill('20')
 check('Changing hypothetical stake updates return',page.locator('.parlay-book').first.inner_text()!=old)
 page.locator('#parlay-save').click();expect(page.locator('.paper-row')).to_have_count(1)
 check('Paper tracker saves without placing a wager','No bet was placed' in page.locator('#toast').inner_text())
 page.locator('[data-paper-result]').select_option('lost')
 check('Manual loss records hypothetical net only','-$20.00' in page.locator('#paper-summary').inner_text())
 page.locator('[data-paper-result]').select_option('void')
 check('Voiding a paper ticket returns hypothetical net to zero','$0.00' in page.locator('#paper-summary').inner_text())
 page.locator('#paper-export').click()
 (OUT/'paper-export.csv').write_text(page.evaluate('()=>window.__export.text()'))
 check('Export includes an explicit hypothetical stake column','hypothetical_stake' in (OUT/'paper-export.csv').read_text())
 page.locator('[data-review-book]').click()
 check('Sportsbook review modal opens',page.locator('#handoff-dialog').evaluate('(d)=>d.open'))
 check('Handoff starts gated',page.locator('#handoff-link').get_attribute('aria-disabled')=='true')
 for c in page.locator('[data-handoff-check]').all():c.check()
 check('Completing review enables explicit external handoff',page.locator('#handoff-link').get_attribute('aria-disabled')=='false')
 check('Handoff is sportsbook homepage, not automatic wager',page.locator('#handoff-link').get_attribute('href').startswith('https://'))
 page.locator('[data-close="handoff-dialog"]').click()
 page.locator('.research-option').first.locator('[data-form-event]').first.click()
 expect(page.locator('.form-card')).to_have_count(2)
 check('Form view displays both teams',page.locator('.form-card').count()==2)
 check('Default form cards list five actual fixture rows',page.locator('.form-card').first.locator('tbody tr').count()==5)
 check('Sample history is labeled at source','Fictional sample history' in page.locator('#form-body').inner_text())
 check('Injuries are not implied verified','not verified' in page.locator('#form-body').inner_text())
 page.screenshot(path=str(OUT/'desktop-form.png'))
 page.locator('[data-close="form-dialog"]').click()
 page.locator('#research-window').select_option('10');page.wait_for_timeout(100)
 page.locator('.research-option').first.locator('[data-form-event]').first.click();expect(page.locator('.form-card').first.locator('tbody tr')).to_have_count(10)
 check('Ten-game option updates score history',page.locator('.form-card').first.locator('tbody tr').count()==10)
 page.locator('[data-close="form-dialog"]').click()
 page.locator('#research-legs').select_option('3');page.wait_for_timeout(100)
 check('Three-leg selector generates three-leg ideas',page.locator('.research-option').first.locator('.research-leg').count()==3)
 page.locator('#research-league').select_option('baseball_mlb');page.wait_for_timeout(100)
 check('Insufficient scope does not invent extra legs',page.locator('.research-option').count()==0)
 page.locator('#research-league').select_option('all');page.locator('#research-legs').select_option('2');page.wait_for_timeout(100)
 page.locator('#research-dialog').evaluate('(d)=>d.scrollTop=0')
 page.screenshot(path=str(OUT/'desktop-research.png'))
 page.locator('[data-remove-leg="0"]').click()
 check('Removing a leg invalidates whole-ticket comparison',page.locator('.parlay-book').count()==0 and page.locator('#parlay-save').is_disabled())
 page.locator('#parlay-clear').click()
 page.locator('[data-close="research-dialog"]').click();page.locator('[data-add-leg]').first.click()
 check('Board outcome adds exact selection',page.locator('.ticket-leg').count()==1)
 page.locator('[data-close="research-dialog"]').click();page.locator('[data-add-leg]').first.click()
 check('Duplicate board selection is rejected',page.locator('.ticket-leg').count()==1 and 'Duplicate' in page.locator('#toast').inner_text())
 store=page.evaluate('window.__store');boot(page,store);page.wait_for_timeout(150);page.locator('.research-banner [data-open="research"]').click()
 check('Paper journal persists when reopening with stored local data',page.locator('.paper-row').count()==1)
 page.locator('[data-paper-remove]').click()
 check('Saved paper ticket can be deleted',page.locator('.paper-row').count()==0)
 for width in [390,768]:
  page.set_viewport_size({'width':width,'height':844});page.wait_for_timeout(100)
  page.locator('#research-analyze').click();expect(page.locator('.research-option')).to_have_count(3)
  page.locator('[data-use-plan="0"]').click()
  check(f'{width}px research modal does not overflow horizontally',page.locator('#research-dialog').evaluate('(d)=>d.scrollWidth<=d.clientWidth+1'))
  check(f'{width}px page does not overflow horizontally',page.evaluate('document.documentElement.scrollWidth<=innerWidth+1'))
  page.locator('#research-dialog').evaluate('(d)=>d.scrollTop=0')
  page.screenshot(path=str(OUT/f'mobile-research-{width}.png'))
  page.locator('#parlay-ticket').scroll_into_view_if_needed();page.screenshot(path=str(OUT/f'mobile-ticket-{width}.png'))
  page.locator('.research-option').first.locator('[data-form-event]').first.click();expect(page.locator('.form-card')).to_have_count(2)
  check(f'{width}px form modal does not overflow horizontally',page.locator('#form-dialog').evaluate('(d)=>d.scrollWidth<=d.clientWidth+1'))
  page.screenshot(path=str(OUT/f'mobile-form-{width}.png'))
  page.locator('[data-close="form-dialog"]').click()
 check('No browser JavaScript errors in parlay flows',not errors)
 (OUT/'research-browser-results.json').write_text(json.dumps({'passed':len(results),'checks':results,'errors':errors,'mode':'Fictional DOM-injected demo. Browser storage and download click are simulated. Chromium, not physical Safari.'},indent=2))
 browser.close()
print(f'\n{len(results)} research browser checks passed. All sports data is fictional; storage and download clicks are simulated.')
